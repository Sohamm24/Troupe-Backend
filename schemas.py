from typing import TypedDict
from pydantic import BaseModel, field_validator
from typing import Optional, List
from datetime import datetime, date

class ImageFeatures(TypedDict):
    # Core feature for visual similarity search
    hsv_histogram: List[float]
    
    # Metadata for content tagging (legacy/extra)
    dominant_colors: Optional[List[List[float]]]
    color_percentages: Optional[List[float]]
    avg_hsv: Optional[List[float]]
    # ... other fields could be added here if needed for legacy compatibility

# ── Location ───────────────────────────────────────────────────────────────────

class LocationModel(BaseModel):
    lat: float
    lng: float
    name: Optional[str] = None


# ── Post schemas ───────────────────────────────────────────────────────────────

import json

class PostResponse(BaseModel):
    """Full post representation returned to the client."""
    id:             int
    user_id:        int
    description:    Optional[str]   = None
    location:       Optional[LocationModel]   = None   # JSON string of Location
    image_url:      str                      # single uploaded image URL
    tags:           Optional[List[str]] = []    # auto-generated by OpenCV
    likes:          int              = 0
    saves:          int              = 0
    trip_start:     Optional[str]    = None  # YYYY-MM-DD
    trip_end:       Optional[str]    = None  # YYYY-MM-DD
    created_at:     Optional[datetime] = None

    @field_validator("location", mode="before")
    @classmethod
    def parse_location_json(cls, v):
        if isinstance(v, str):
            try:
                return json.loads(v)
            except (json.JSONDecodeError, TypeError):
                return None
        return v

    model_config = {"from_attributes": True}


# ── User schemas ───────────────────────────────────────────────────────────────

class User(BaseModel):
    id:         int
    external_id:   str
    username:   Optional[str]    = None
    first_name: Optional[str]    = None
    last_name:  Optional[str]    = None
    profile_pic_url: Optional[str]    = None
    onboarded:  bool             = False
    created_at: Optional[datetime] = None
    posts:      List[PostResponse] = []

    model_config = {"from_attributes": True}



class FeedResponse(BaseModel):
    """Feed pagination response format"""
    total: int
    returned: int
    offset: int
    limit: int
    posts: List[PostResponse]
