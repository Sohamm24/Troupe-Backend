"""
migrate_db.py
-------------
Additive migrations using ALTER TABLE … ADD COLUMN IF NOT EXISTS.
Safe to run multiple times (idempotent).

History:
  v1 — users table columns (username, first_name, last_name, avatar_url, onboarded)
  v2 — posts table overhaul for new CreatePost schema:
         • image_url      (single URL, replaces image_urls array)
         • location       changed to TEXT to store JSON string
         • tags           TEXT[] auto-generated by OpenCV
         • likes          INT engagement counter
         • saves          INT engagement counter
         • trip_start     VARCHAR trip start date (YYYY-MM-DD)
         • trip_end       VARCHAR trip end date   (YYYY-MM-DD)
  v3 — Renames & JSONB:
         • users.avatar_url   → profile_pic_url
         • users.clerk_id     → external_id
         • posts.location      → JSONB
"""

import os
from sqlalchemy import text
from database import engine


def migrate_v1_users(conn) -> None:
    """v1: Add optional columns to the users table."""
    stmts = [
        "ALTER TABLE users ADD COLUMN IF NOT EXISTS username   VARCHAR UNIQUE;",
        "ALTER TABLE users ADD COLUMN IF NOT EXISTS first_name VARCHAR;",
        "ALTER TABLE users ADD COLUMN IF NOT EXISTS last_name  VARCHAR;",
        "ALTER TABLE users ADD COLUMN IF NOT EXISTS profile_pic_url VARCHAR;",
        "ALTER TABLE users ADD COLUMN IF NOT EXISTS onboarded  BOOLEAN DEFAULT FALSE NOT NULL;",
        # Make email nullable for privacy
        "ALTER TABLE users ALTER COLUMN email DROP NOT NULL;",
    ]
    for stmt in stmts:
        conn.execute(text(stmt))
    print("  [v1] users table — OK")


def migrate_v2_posts(conn) -> None:
    """
    v2: Extend the posts table with new columns needed by the
    updated CreatePostScreen and feed scoring logic.

    NOTE ON image_url vs image_urls
    --------------------------------
    The old model stored multiple URLs in a PostgreSQL TEXT[] column called
    image_urls.  The new model uses a single TEXT column called image_url.

    • image_url is added as nullable so existing rows don't break.
    • image_urls is left untouched — we don't drop data we can't restore.
    • After running this migration you can backfill image_url from image_urls
      with the one-liner at the bottom of this file if you have existing rows.
    """
    stmts = [
        # Single image URL (nullable so existing rows are unaffected)
        "ALTER TABLE posts ADD COLUMN IF NOT EXISTS image_url  TEXT;",

        # Location as a JSON string (e.g. {"name":"Paris","lat":48.8,"lng":2.3})
        # The old column was VARCHAR — keep it and also accept TEXT via ALTER TYPE
        "ALTER TABLE posts ALTER COLUMN location TYPE TEXT USING location::TEXT;",

        # Auto-generated travel tags (array of strings)
        "ALTER TABLE posts ADD COLUMN IF NOT EXISTS tags       TEXT[];",

        # Engagement counters
        "ALTER TABLE posts ADD COLUMN IF NOT EXISTS likes      INTEGER NOT NULL DEFAULT 0;",
        "ALTER TABLE posts ADD COLUMN IF NOT EXISTS saves      INTEGER NOT NULL DEFAULT 0;",

        # Trip duration stored as plain date strings (YYYY-MM-DD)
        "ALTER TABLE posts ADD COLUMN IF NOT EXISTS trip_start VARCHAR;",
        "ALTER TABLE posts ADD COLUMN IF NOT EXISTS trip_end   VARCHAR;",
    ]
    for stmt in stmts:
        conn.execute(text(stmt))

    # Backfill image_url for rows that have image_urls but no image_url yet.
    # Takes the first element of the old array so existing posts remain visible.
    conn.execute(text("""
        DO $$
        BEGIN
            IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='posts' AND column_name='image_urls') THEN
                UPDATE posts
                SET    image_url = image_urls[1]
                WHERE  image_url IS NULL
                  AND  image_urls IS NOT NULL
                  AND  array_length(image_urls, 1) > 0;
            END IF;
        END $$;
    """))
    print("  [v2] posts table — OK")


def migrate_v3_cleanup(conn) -> None:
    """v3: Rename columns to match latest models and convert types."""
    
    # 1. users: avatar_url -> profile_pic_url
    conn.execute(text("""
        DO $$
        BEGIN
            -- If both exist, copy data from old to new and drop old
            IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='users' AND column_name='avatar_url') 
               AND EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='users' AND column_name='profile_pic_url') THEN
                UPDATE users SET profile_pic_url = avatar_url WHERE profile_pic_url IS NULL;
                ALTER TABLE users DROP COLUMN avatar_url;
            -- If only old exists, rename it
            ELSIF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='users' AND column_name='avatar_url') THEN
                ALTER TABLE users RENAME COLUMN avatar_url TO profile_pic_url;
            END IF;
        END $$;
    """))

    # 2. users: clerk_id -> external_id (if not already renamed)
    conn.execute(text("""
        DO $$
        BEGIN
            IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='users' AND column_name='clerk_id') 
               AND EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='users' AND column_name='external_id') THEN
                UPDATE users SET external_id = clerk_id WHERE external_id IS NULL;
                ALTER TABLE users DROP COLUMN clerk_id;
            ELSIF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='users' AND column_name='clerk_id') THEN
                ALTER TABLE users RENAME COLUMN clerk_id TO external_id;
            END IF;
        END $$;
    """))

    # 3. posts: location TEXT -> JSONB
    # We use USING to safely cast valid JSON strings to JSONB
    conn.execute(text("""
        ALTER TABLE posts 
        ALTER COLUMN location TYPE JSONB 
        USING location::JSONB;
    """))

    print("  [v3] renames & JSONB conversion — OK")


def migrate_v4_visual_search(conn) -> None:
    """v4: Add image_features JSONB to posts for visual similarity search."""
    conn.execute(text("""
        ALTER TABLE posts 
        ADD COLUMN IF NOT EXISTS image_features JSONB;
    """))
    print("  [v4] image_features column — OK")


def migrate_v5_social_and_media(conn) -> None:
    """v5: Add tables for likes/saves, and new columns for multiple images & trip days."""
    
    # 1. posts table changes
    stmts = [
        # Make image_url optional for new posts
        "ALTER TABLE posts ALTER COLUMN image_url DROP NOT NULL;",
        # Add media_urls as JSONB
        "ALTER TABLE posts ADD COLUMN IF NOT EXISTS media_urls JSONB DEFAULT '[]'::JSONB;",
        # Add trip_days
        "ALTER TABLE posts ADD COLUMN IF NOT EXISTS trip_days INTEGER;"
    ]
    for stmt in stmts:
        conn.execute(text(stmt))

    # 2. Backfill media_urls with image_url if empty
    conn.execute(text("""
        UPDATE posts 
        SET media_urls = jsonb_build_array(image_url) 
        WHERE image_url IS NOT NULL 
          AND (media_urls IS NULL OR jsonb_array_length(media_urls) = 0);
    """))

    # 3. Create post_likes table
    conn.execute(text("""
        CREATE TABLE IF NOT EXISTS post_likes (
            id SERIAL PRIMARY KEY,
            user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            post_id INTEGER NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
            created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
            CONSTRAINT uq_post_like_user_post UNIQUE (user_id, post_id)
        );
    """))

    # 4. Create post_saves table
    conn.execute(text("""
        CREATE TABLE IF NOT EXISTS post_saves (
            id SERIAL PRIMARY KEY,
            user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            post_id INTEGER NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
            created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
            CONSTRAINT uq_post_save_user_post UNIQUE (user_id, post_id)
        );
    """))

    print("  [v5] social tables & media columns — OK")


def migrate() -> None:
    print("Running database migrations…")
    with engine.begin() as conn:          # auto-commits on success, rolls back on error
        migrate_v1_users(conn)
        migrate_v2_posts(conn)
        migrate_v3_cleanup(conn)
        migrate_v4_visual_search(conn)
        migrate_v5_social_and_media(conn)
    print("[DONE] All migrations applied successfully.")


if __name__ == "__main__":
    migrate()
